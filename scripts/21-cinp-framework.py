"""
21-cinp-framework.py — CINP Framework: Outcome Reclassification Documentation

Reframes the primary outcome from "Medically Important Brain Attack (MI)" to a
decision-based composite:
    - CINP (Clinically Important Neurologic Presentation) — primary outcome:
      "who requires urgent neurodiagnostic investigation?"
    - CIIP (Clinically Important Intracranial Pathology) — secondary outcome:
      confirmed intracranial pathology requiring treatment

Key insight: CINP = 147 cases (= original MI), because:
    - All CIIP cases (121) qualify via criterion 1 (confirmed intracranial pathology)
    - All 26 cerebellar ataxia cases qualify via criterion 2 (documented ataxia =
      objective neurologic finding mandating investigation to exclude posterior
      fossa tumour, ADEM, stroke)
    - No reanalysis is needed: existing MI results become CINP results, and CIIP
      results are already generated by scripts 17-20.

CINP Definition (two criteria, either sufficient):
    Criterion 1: Confirmed intracranial pathology requiring treatment, imaging
                 surveillance, or specialist referral (= CIIP outcome)
    Criterion 2: Documented objective neurologic finding on clinical assessment
                 that mandates urgent neurodiagnostic investigation to exclude
                 serious intracranial pathology, regardless of final diagnosis

Circularity guardrails:
    - CINP is NOT defined by imaging ordered, neurology consulted, or admission
    - Objective findings must be present in the clinical record
    - Cases with investigation but no documented objective findings are flagged

Inputs:
    data/processed/brain_attacks_combined.parquet  (MI dataset, 147 events)
    data/processed/brain_attacks_ciip.parquet       (CIIP dataset, 121 events)

Outputs:
    data/processed/brain_attacks_cinp.parquet
    outputs/tables/table_cinp_adjudication.csv
    outputs/tables/table_cinp_vs_mi_vs_ciip.csv
    outputs/cinp_methods_text.md
"""

