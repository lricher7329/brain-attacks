# 3. ADJUDICATION TABLE
# ===================================================================

def build_adjudication_table(df):
    """Build per-case adjudication table for all MI cases."""
    _print("\n=== Building Adjudication Table ===")

    mi_mask = df["outcome_med_important"] == 1
    mi_df = df[mi_mask].copy()

    rows = []
    for idx in mi_df.index:
        row = df.loc[idx]

        # Get all MI diagnosis codes
        dx_codes = []
        for code in range(1, 14):
            col = f"med_imp_dx___{code}"
            if col in df.columns and row.get(col, 0) == 1:
                dx_codes.append(MI_DX_LABELS.get(code, f"Code {code}"))

        # Objective findings present
        findings = []
        for col, label in OBJECTIVE_FINDINGS.items():
            if col in df.columns and row.get(col, 0) == 1:
                findings.append(label)

        # Imaging
        results_val = row.get("results", np.nan)
        abnormal_imaging = (results_val == 2) if pd.notna(results_val) else False

        # Treatment
        has_tx = row.get("inv_specific_tx", 0) == 1

        rows.append({
            "record_id": row.get("record_id", idx),
            "year": int(row.get("year", 0)),
            "age": round(row.get("age", 0), 1),
            "mi_diagnoses": "; ".join(dx_codes),
            "original_mi": 1,
            "objective_findings": "; ".join(findings) if findings else "None documented",
            "n_objective_findings": len(findings),
            "abnormal_imaging": int(abnormal_imaging),
            "specific_treatment": int(has_tx),
            "cinp_status": int(row["outcome_cinp"]),
            "ciip_status": int(row["outcome_ciip"]),
            "cinp_criterion": row["cinp_criterion"],
            "reason": row["cinp_reason"],
        })

    tbl = pd.DataFrame(rows)
    tbl.to_csv(TABLES / "table_cinp_adjudication.csv", index=False)

    _print(f"  Saved table_cinp_adjudication.csv ({len(tbl)} rows)")
    _print(f"  CINP=1: {(tbl['cinp_status'] == 1).sum()}")
    _print(f"  CIIP=1: {(tbl['ciip_status'] == 1).sum()}")
    _print(f"  Criterion 1 (CIIP): {(tbl['cinp_criterion'] == 'Criterion 1').sum()}")
    _print(f"  Criterion 2 (objective finding): {(tbl['cinp_criterion'] == 'Criterion 2').sum()}")
    _print(f"  FLAGGED: {(tbl['cinp_criterion'] == 'FLAGGED').sum()}")

    # Show the criterion 2 cases (CA cases with objective findings)
    crit2 = tbl[tbl["cinp_criterion"] == "Criterion 2"]
    if len(crit2) > 0:
        _print(f"\n  --- Criterion 2 Cases (n={len(crit2)}) ---")
        for _, r in crit2.iterrows():
            _print(f"    Record {r['record_id']}: {r['mi_diagnoses']} | "
                   f"Findings: {r['objective_findings']}")

    return tbl


