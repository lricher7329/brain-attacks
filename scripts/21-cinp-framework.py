def load_data():
    """Load both MI and CIIP datasets."""
    _print("=== Loading Data ===")

    df_mi = pd.read_parquet(DATA / "brain_attacks_combined.parquet")
    df_mi["year"] = pd.to_numeric(df_mi["year"], errors="coerce")

    df_ciip = pd.read_parquet(DATA / "brain_attacks_ciip.parquet")
    df_ciip["year"] = pd.to_numeric(df_ciip["year"], errors="coerce")

    n_mi = (df_mi["outcome_med_important"] == 1).sum()
    n_ciip = (df_ciip["outcome_ciip"] == 1).sum()
    _print(f"  MI dataset: {len(df_mi)} records, {n_mi} MI events")
    _print(f"  CIIP dataset: {len(df_ciip)} records, {n_ciip} CIIP events")

    return df_mi, df_ciip


# ===================================================================
# 2. CLASSIFY CINP
# ===================================================================

def classify_cinp(df_mi, df_ciip):
    """Apply CINP classification to all records.

    For each of 147 MI cases:
        1. Check CIIP status (from ciip dataset)
        2. If CIIP -> CINP=1, CIIP=1, reason="CIIP-qualifying pathology"
        3. If not CIIP (26 CA cases):
           - Check objective neurologic findings
           - If any present -> CINP=1, CIIP=0, reason="Objective finding: [field]"
           - If none -> CINP=0, CIIP=0, flag for PI review
        4. All non-MI cases -> CINP=0, CIIP=0
    """
    _print("\n=== Classifying CINP ===")

    # Merge CIIP status into MI dataset
    df = df_mi.copy()
    df["outcome_ciip"] = df_ciip["outcome_ciip"].values

    # Initialize CINP columns
    df["outcome_cinp"] = 0
    df["cinp_reason"] = ""
    df["cinp_criterion"] = ""
    df["cinp_objective_findings"] = ""

    mi_mask = df["outcome_med_important"] == 1
    ciip_mask = df["outcome_ciip"] == 1

    # --- MI cases that are also CIIP -> CINP via criterion 1 ---
    mi_ciip_mask = mi_mask & ciip_mask
    df.loc[mi_ciip_mask, "outcome_cinp"] = 1
    df.loc[mi_ciip_mask, "cinp_criterion"] = "Criterion 1"

    # Get diagnosis labels for CIIP cases
    for idx in df.index[mi_ciip_mask]:
        dx_codes = []
        for code in range(1, 14):
            col = f"med_imp_dx___{code}"
            if col in df.columns and df.loc[idx, col] == 1:
                dx_codes.append(MI_DX_LABELS.get(code, f"Code {code}"))
        df.loc[idx, "cinp_reason"] = f"CIIP-qualifying pathology: {'; '.join(dx_codes)}"

    n_ciip_cinp = mi_ciip_mask.sum()
    _print(f"  CIIP -> CINP (criterion 1): {n_ciip_cinp}")

    # --- MI cases that are NOT CIIP (CA-only cases) ---
    mi_not_ciip_mask = mi_mask & ~ciip_mask
    n_non_ciip_mi = mi_not_ciip_mask.sum()
    _print(f"  MI but not CIIP (CA cases to evaluate): {n_non_ciip_mi}")

    n_criterion2 = 0
    n_flagged = 0

    for idx in df.index[mi_not_ciip_mask]:
        row = df.loc[idx]

        # Check all objective findings
        present_findings = []
        for col, label in OBJECTIVE_FINDINGS.items():
            if col in df.columns and row.get(col, 0) == 1:
                present_findings.append(f"{col} ({label})")

        if present_findings:
            df.loc[idx, "outcome_cinp"] = 1
            df.loc[idx, "cinp_criterion"] = "Criterion 2"
            df.loc[idx, "cinp_reason"] = f"Objective finding: {'; '.join(present_findings)}"
            df.loc[idx, "cinp_objective_findings"] = "; ".join(present_findings)
            n_criterion2 += 1
        else:
            # No objective findings documented -> flag for PI review
            df.loc[idx, "outcome_cinp"] = 0
            df.loc[idx, "cinp_criterion"] = "FLAGGED"
            df.loc[idx, "cinp_reason"] = "MI case with no documented objective finding — requires PI review"
            n_flagged += 1

    _print(f"  Objective finding -> CINP (criterion 2): {n_criterion2}")
    _print(f"  FLAGGED (no objective finding): {n_flagged}")

    # Final counts
    n_cinp = (df["outcome_cinp"] == 1).sum()
    n_ciip_final = (df["outcome_ciip"] == 1).sum()
    _print(f"\n  Final CINP count: {n_cinp}")
    _print(f"  Final CIIP count: {n_ciip_final}")
    _print(f"  CINP prevalence: {100 * n_cinp / len(df):.1f}%")
    _print(f"  CIIP prevalence: {100 * n_ciip_final / len(df):.1f}%")

    return df


