def generate_methods_text(df):
    """Generate publication-ready methods paragraph for CINP/CIIP."""
    _print("\n=== Generating Methods Text ===")

    n_cinp = (df["outcome_cinp"] == 1).sum()
    n_ciip = (df["outcome_ciip"] == 1).sum()
    n_criterion1 = ((df["outcome_cinp"] == 1) & (df["outcome_ciip"] == 1)).sum()
    n_criterion2 = ((df["outcome_cinp"] == 1) & (df["outcome_ciip"] == 0)).sum()
    total = len(df)

    text = f"""# CINP/CIIP Outcome Definitions — Methods Text

## Primary Outcome: Clinically Important Neurologic Presentation (CINP)

The primary outcome was clinically important neurologic presentation (CINP), \
defined as an acute neurologic presentation requiring urgent neurodiagnostic \
investigation. CINP was ascertained using two criteria (either sufficient):

**Criterion 1 — Confirmed intracranial pathology (CIIP):** Any of the following \
diagnoses confirmed by the treating team: stroke, intracranial haemorrhage, \
vascular malformation, vasculitis, cerebral venous thrombosis, demyelinating \
disorder, brain or meningeal infection, hydrocephalus, neoplasm, inborn error \
of metabolism, idiopathic intracranial hypertension (IIH), or other clinically \
important intracranial pathology requiring treatment, imaging surveillance, or \
specialist referral.

**Criterion 2 — Objective neurologic finding mandating investigation:** \
Documented objective neurologic finding on clinical assessment (cerebellar \
ataxia, focal weakness, sensory disturbance, speech disturbance, visual \
disturbance, eye movement abnormality, altered consciousness, altered level \
of consciousness on examination, papilledema, meningismus, or seizure) in a \
patient whose final diagnosis did not meet criterion 1 but whose presentation \
mandated urgent neurodiagnostic investigation to exclude serious intracranial \
pathology.

Of {n_cinp} CINP cases ({100*n_cinp/total:.1f}% prevalence), \
{n_criterion1} met criterion 1 (confirmed intracranial pathology) and \
{n_criterion2} met criterion 2 only (objective neurologic finding without \
confirmed pathology). All {n_criterion2} criterion 2 cases had cerebellar \
ataxia as the qualifying objective finding; these cases required neuroimaging \
to exclude posterior fossa tumour, acute disseminated encephalomyelitis, and \
stroke, but were ultimately diagnosed with acute post-infectious cerebellar \
ataxia — a self-limiting condition not meeting CIIP criteria.

## Secondary Outcome: Clinically Important Intracranial Pathology (CIIP)

The secondary outcome was clinically important intracranial pathology (CIIP), \
defined as confirmed intracranial pathology requiring specific treatment, \
imaging surveillance, or specialist referral (CINP criterion 1 above). CIIP \
excludes cases meeting only criterion 2, as these represent presentations \
where investigation was clinically mandated but no treatable intracranial \
pathology was identified. CIIP comprised {n_ciip} cases \
({100*n_ciip/total:.1f}% prevalence).

## Circularity Avoidance

CINP criterion 2 was defined using objective neurologic findings documented \
in the clinical record (symptoms and examination findings), not by \
investigation ordering, specialist consultation, or hospital admission \
decisions. This avoids circularity between the outcome (who needs \
investigation) and the clinical decisions that the prediction model is \
intended to inform.

## Rationale

This two-tier outcome structure parallels established paediatric emergency \
medicine composite endpoints such as the PECARN clinically important \
traumatic brain injury (ciTBI) definition, which similarly combines confirmed \
pathology cases with clinically concerning presentations requiring acute \
intervention. The CINP definition captures the full population for whom the \
clinical decision (to investigate urgently) is relevant, while CIIP provides \
a strict pathology-confirmed endpoint for sensitivity analysis.

## Sensitivity Analysis Structure

- **Primary analysis:** CINP ({n_cinp} events) — the decision-relevant population
- **Sensitivity analysis 1:** CIIP ({n_ciip} events) — strict pathology endpoint
- **Sensitivity analysis 2:** CIIP excluding IIH — pathology endpoint without \
IIH (included because clinical debate exists regarding IIH classification)
"""

    with open(OUTPUTS / "cinp_methods_text.md", "w") as f:
        f.write(text)

    _print(f"  Saved cinp_methods_text.md")

    return text


